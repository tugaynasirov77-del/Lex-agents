def main() -> int:
    here = Path(__file__).resolve().parent
    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        raise ValueError("ANTHROPIC_API_KEY не найден!")
    print(f"Ключ найден: {api_key[:10]}... (length={len(api_key)})")

    config = json.loads((here / "agents_config.json").read_text())
    agents: dict[str, str] = config["agents"]

    client = Anthropic(
        api_key=api_key,
        default_headers={"anthropic-beta": BETA_HEADER},
        timeout=120.0,
        max_retries=3,
    )

    results: list[tuple[str, str, int]] = []
    for name, agent_id in agents.items():
        prompt = PROMPTS.get(name)
        if not prompt:
            results.append((name, "SKIP (no prompt)", -1))
            continue
        # The orchestrator's output is consumed by code as JSON; the
        # "plain text, no markdown" instruction confuses it (it stops emitting
        # JSON). Skip the suffix for orchestrator.
        if name != "orchestrator" and NO_MARKDOWN_SUFFIX.strip() not in prompt:
            prompt = prompt.rstrip() + NO_MARKDOWN_SUFFIX
        if (name in COLLABORATION_AGENTS
                and "КОМАНДНАЯ РАБОТА" not in prompt):
            prompt = prompt.rstrip() + COLLABORATION_HINT

        last_err: Exception | None = None
        for attempt in range(1, 4):
            try:
                current = client.beta.agents.retrieve(agent_id)
                if getattr(current, "system", None) == prompt:
                    results.append((name, "OK (no change)", current.version))
                    break
                updated = client.beta.agents.update(
                    agent_id, version=current.version, system=prompt
                )
                results.append(
                    (name, f"OK (v{current.version} → v{updated.version})",
                     updated.version)
                )
                break
            except Exception as e:
                last_err = e
                time.sleep(2 * attempt)
        else:
            results.append((name, f"ERROR: {type(last_err).__name__}: {last_err}", -1))

    print(f"\n{'AGENT':<16} {'VERSION':<10} STATUS")
    print("-" * 70)
    for name, status, ver in results:
        v = f"v{ver}" if ver > 0 else "—"
        print(f"{name:<16} {v:<10} {status}")
    return 0 if all(s.startswith("OK") for _, s, _ in results) else 1


