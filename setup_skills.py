def write_skill_files() -> dict[str, dict[str, Path]]:
    """Materialise all SKILL.md files. Returns {agent_folder: {slug: path}}."""
    out: dict[str, dict[str, Path]] = {}
    skills_root = HERE / "skills"
    skills_root.mkdir(exist_ok=True)

    for folder, items in SKILLS.items():
        agent_dir = skills_root / folder
        agent_dir.mkdir(exist_ok=True)
        out[folder] = {}
        for slug, description, body in items:
            skill_dir = agent_dir / slug
            skill_dir.mkdir(exist_ok=True)
            content = (
                f"---\n"
                f"name: {slug}\n"
                f"description: {description.strip()}\n"
                f"---\n\n"
                f"{body.strip()}\n"
            )
            path = skill_dir / "SKILL.md"
            path.write_text(content, encoding="utf-8")
            out[folder][slug] = path
    return out


