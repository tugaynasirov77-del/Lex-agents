def upload_skill(client: Anthropic, skill_dir: Path, display: str) -> str:
    """Upload one skill folder. Returns skill_id."""
    skill = client.beta.skills.create(
        display_title=display,
        files=files_from_dir(str(skill_dir)),
        extra_headers={"anthropic-beta": "skills-2025-10-02"},
    )
    return skill.id


# =================================================================== attach

def attach_skills_to_agent(client: Anthropic, agent_id: str,
                           skill_ids: list[str]) -> Optional[int]:
    """Attach the given custom skills (replacing any existing) to the agent."""
    skills_payload = [
        {"type": "custom", "skill_id": sid, "version": "latest"}
        for sid in skill_ids
    ]
    last_err: Optional[Exception] = None
    for attempt in range(1, 4):
        try:
            current = client.beta.agents.retrieve(agent_id)
            updated = client.beta.agents.update(
                agent_id, version=current.version, skills=skills_payload,
            )
            return updated.version
        except Exception as e:
            last_err = e
            time.sleep(2 * attempt)
    log_warning = f"attach failed: {type(last_err).__name__}: {last_err}"
    print(f"  WARN: {log_warning}", file=sys.stderr)
    return None


